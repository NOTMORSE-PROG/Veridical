"""F8 print projections of persisted evidence, without private annotations."""

from app.flags.schemas import FlagOut
from app.report.schemas import ExportComparisonOut, FlagExportDetailOut, UnassessedReferenceOut


def flag_export_detail(
    flag: FlagOut, *, recorded_detail: dict | None = None, recorded_excerpt: str | None = None
) -> FlagExportDetailOut:
    detail = recorded_detail or {}
    kind = detail.get("kind")
    reuse = flag.check_kind == "originality_reuse"
    evidence_is_summary = reuse and kind in (
        "reuse_exact_duplicate",
        "reuse_high_similarity",
        "reuse_exact_duplicate_chapter",
        "reuse_high_similarity_chapter",
        "reuse_same_instructor_resubmission",
    )
    reasoning = flag.ai_reasoning
    current_guidance = None
    recorded_explanation_withheld = False
    if reuse and isinstance(kind, str) and kind.startswith("reuse_") and reasoning:
        recorded_reason = detail.get("reasoning") or detail.get("reason")
        if reasoning != recorded_reason:
            # Public reuse wording may be generated by the current non-scoring
            # policy. Do not falsely call it a saved explanation, nor restore
            # arbitrary legacy reasons with obsolete/identifying language.
            current_guidance, reasoning = reasoning, None
            recorded_explanation_withheld = (
                isinstance(recorded_reason, str)
                and bool(recorded_reason.strip())
                and recorded_reason != recorded_excerpt
            )
    comparisons = []
    if (
        flag.check_kind == "citation_integrity"
        and flag.ai_verdict_summary == "possible_metadata_mismatch"
    ):
        if metadata := flag.citation_metadata_comparison:
            comparisons.append(
                ExportComparisonOut(label="Recorded registry comparison", text=metadata.provider)
            )
            comparisons.append(
                ExportComparisonOut(
                    label="Fields marked different by the saved check"
                    if flag.citation_metadata_review_warning
                    else "Fields marked different",
                    text=", ".join(metadata.differing_fields) or "Not recorded",
                )
            )
            for key, label in (
                ("doi", "DOI"),
                ("title", "Title"),
                ("year", "Year"),
                ("first_author", "First author"),
            ):
                for values, origin in (
                    (metadata.cited, "In manuscript reference"),
                    (metadata.registered, "Returned by provider"),
                ):
                    value = getattr(values, key)
                    comparisons.append(
                        ExportComparisonOut(
                            label=f"{origin} - {label}",
                            text=str(value) if value is not None else "Not recorded",
                        )
                    )
            for label, value in (
                ("DOI source", metadata.doi_source_url),
                ("Provider record", metadata.provider_record_url),
                ("Comparison policy", metadata.policy_version),
                ("Policy SHA256", metadata.policy_sha256),
                ("Snapshot schema", metadata.schema_version),
            ):
                comparisons.append(
                    ExportComparisonOut(label=label, text=str(value) if value else "Not recorded")
                )
            comparisons.append(
                ExportComparisonOut(
                    label="Comparison limit",
                    text=(
                        "Source existence does not establish support for a manuscript claim. "
                        "Links open current external records; "
                        "the comparison above is saved evidence."
                    ),
                )
            )
            comparisons.append(
                ExportComparisonOut(label="Title comparison", text=metadata.title_status)
            )
            if metadata.unassessed_reason:
                comparisons.append(
                    ExportComparisonOut(
                        label="Unassessed comparison reason", text=metadata.unassessed_reason
                    )
                )
        else:
            comparisons.append(
                ExportComparisonOut(
                    label="Provider comparison was not saved",
                    text=(
                        "This historical finding does not include the provider metadata used "
                        "for comparison. Run a new check to create a new evidence record, "
                        "or verify the source independently."
                    ),
                )
            )
    if pair := flag.agreement_pair:
        comparisons.extend(
            [
                ExportComparisonOut(
                    label="Candidate objective",
                    text=pair.intent_text,
                    anchor=pair.intent_anchor,
                ),
                ExportComparisonOut(
                    label="Candidate result",
                    text=pair.outcome_text,
                    anchor=pair.outcome_anchor,
                ),
            ]
        )
    if values := flag.p_value_comparison:
        comparisons.extend(
            [
                ExportComparisonOut(label="Reported p-value", text=values.reported),
                ExportComparisonOut(label="Recalculated p-value", text=values.recalculated),
            ]
        )
    if passages := flag.passage_pair:
        # The same bounded excerpts shown on screen, not matched-source file access.
        for label, excerpt, before, after, anchor in (
            (
                "This manuscript",
                passages.own_excerpt,
                passages.own_context_before,
                passages.own_context_after,
                flag.page_anchor,
            ),
            (
                f"Library match {passages.matched_ref}",
                passages.matched_excerpt,
                passages.matched_context_before,
                passages.matched_context_after,
                None,
            ),
        ):
            comparisons.append(ExportComparisonOut(label=label, text=excerpt, anchor=anchor))
            if before:
                comparisons.append(
                    ExportComparisonOut(label=f"{label}, preceding context", text=before)
                )
            if after:
                comparisons.append(
                    ExportComparisonOut(label=f"{label}, following context", text=after)
                )
    source = flag.citation_source_key
    return FlagExportDetailOut(
        citation_metadata_review_warning=flag.citation_metadata_review_warning,
        issue=flag.ai_verdict_summary,
        reasoning=reasoning,
        source_identifier=f"{source.kind}: {source.value}" if source else None,
        comparisons=comparisons,
        override_reason=flag.override_reason if flag.overridden else None,
        evidence_unavailable=flag.evidence_unavailable
        or (evidence_is_summary and flag.passage_pair is None),
        evidence_is_summary=evidence_is_summary,
        current_guidance=current_guidance,
        recorded_explanation_withheld=recorded_explanation_withheld,
    )


def unassessed_references(detail: dict) -> list[UnassessedReferenceOut]:
    """Read only the run's coverage ledger. Never infer a provider result from flags."""
    ledger = detail.get("reference_metadata_coverage")
    if not isinstance(ledger, list):
        return []
    records = []
    for row in ledger:
        if not isinstance(row, dict):
            continue
        index = row.get("reference_order_index")
        if type(index) is not int or index < 0:
            continue
        status = row.get("status")
        comparison = row.get("metadata_comparison")
        title_unassessed = (
            isinstance(comparison, dict) and comparison.get("title_status") == "unassessed"
        )
        if (
            status not in ("unassessed", "api_down")
            and row.get("metadata_complete") is not False
            and not title_unassessed
        ):
            continue
        if not isinstance(status, str) or type(row.get("lookup_attempted")) is not bool:
            continue
        reason = row.get("reason") or (
            comparison.get("unassessed_reason") if title_unassessed else None
        )
        records.append(
            UnassessedReferenceOut(
                reference_order_index=index,
                status=status,
                reason=reason if isinstance(reason, str) else None,
                lookup_attempted=row["lookup_attempted"],
            )
        )
    return records
